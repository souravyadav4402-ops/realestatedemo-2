const fmtPrice = (p, status) => {
  if (status === 'rent') {
    return `$${p.toLocaleString('en-US')}<span class="per">/mo</span>`;
  }
  return `$${p.toLocaleString('en-US')}`;
};

const fmtPriceShort = (p, status) => {
  if (status === 'rent') return `$${(p / 1000).toFixed(0)}K/mo`;
  if (p >= 1000000) return `$${(p / 1000000).toFixed(p >= 10000000 ? 1 : 2)}M`;
  return `$${(p / 1000).toFixed(0)}K`;
};

const daysOnMarket = (listed) => {
  const then = new Date(listed);
  const now = new Date('2026-09-06');
  return Math.max(1, Math.round((now - then) / 86400000));
};

